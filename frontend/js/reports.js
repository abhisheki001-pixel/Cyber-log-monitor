/* =========================================================================
   reports.js — Logic for reports.html (Security Reports page)
   ========================================================================= */

const REPORT_TYPES = [
  "Daily Security Report",
  "Weekly Security Report",
  "Monthly Security Report",
  "Alert Summary",
  "Login Activity Report",
  "IP Activity Report",
];

let selectedReport = REPORT_TYPES[0];
let currentPreview = null;

document.addEventListener("DOMContentLoaded", () => {
  renderReportTypeCards();
  generateReport(selectedReport);

  document.getElementById("downloadCsvBtn").addEventListener("click", () => downloadReport("csv"));
  document.getElementById("downloadPdfBtn").addEventListener("click", () => downloadReport("pdf"));
});

function renderReportTypeCards() {
  document.getElementById("reportTypeGrid").innerHTML = REPORT_TYPES.map(
    (type) => `
      <div class="card" style="cursor:pointer; border-color:${type === selectedReport ? "var(--accent)" : "var(--border)"};" onclick="selectReport('${type}')">
        <div class="stat-icon">📄</div>
        <div class="stat-label" style="font-size:13.5px;color:var(--text-hi);">${type}</div>
        <button class="btn btn-sm btn-primary" style="margin-top:10px;">Generate Report</button>
      </div>`
  ).join("");
}

function selectReport(type) {
  selectedReport = type;
  renderReportTypeCards();
  generateReport(type);
}

function generateReport(type) {
  document.getElementById("reportPreview").innerHTML = `<div class="state-msg">Loading security events…</div>`;
  CyberLogAPI.getReportPreview(type).then((data) => {
    currentPreview = data;
    document.getElementById("reportPreview").innerHTML = `
      <p class="page-subtitle" style="margin-bottom:16px;">${type} · ${data.reportingPeriod}</p>
      <div class="detail-grid">
        <div><div class="k">Total Events</div><div class="v">${data.totalEvents.toLocaleString()}</div></div>
        <div><div class="k">Successful Logins</div><div class="v">${data.successfulLogins.toLocaleString()}</div></div>
        <div><div class="k">Failed Logins</div><div class="v">${data.failedLogins}</div></div>
        <div><div class="k">Total Alerts</div><div class="v">${data.totalAlerts}</div></div>
        <div><div class="k">Critical Alerts</div><div class="v">${data.criticalAlerts}</div></div>
        <div><div class="k">High Alerts</div><div class="v">${data.highAlerts}</div></div>
        <div><div class="k">Medium Alerts</div><div class="v">${data.mediumAlerts}</div></div>
        <div><div class="k">Low Alerts</div><div class="v">${data.lowAlerts}</div></div>
      </div>
      <div class="grid-2">
        <div><div class="k" style="margin-bottom:6px;">Top Alert Types</div>
          <ul style="margin:0;padding-left:18px;font-size:13px;color:var(--text-mid);">
            ${data.topAlertTypes.map((t) => `<li>${t}</li>`).join("")}
          </ul>
        </div>
        <div><div class="k" style="margin-bottom:6px;">Top Active IPs</div>
          <ul style="margin:0;padding-left:18px;font-size:13px;color:var(--text-mid);" class="mono">
            ${data.topActiveIps.map((ip) => `<li>${ip}</li>`).join("")}
          </ul>
        </div>
      </div>`;
  });
}

function downloadReport(format) {
  if (!currentPreview) return;
  // A real backend would generate the CSV/PDF server-side (e.g. GET /api/reports?format=pdf).
  // For the demo we just export the preview data as CSV, and simulate PDF with a toast.
  if (format === "csv") {
    const rows = Object.entries(currentPreview)
      .filter(([, v]) => !Array.isArray(v))
      .map(([k, v]) => `${k},${v}`)
      .join("\n");
    const blob = new Blob([rows], { type: "text/csv" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = "security-report.csv";
    link.click();
    URL.revokeObjectURL(url);
    showToast("Report downloaded as CSV");
  } else {
    showToast("PDF export will be generated by the Flask backend");
  }
}
